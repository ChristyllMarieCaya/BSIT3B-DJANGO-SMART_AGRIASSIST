from django.conf import settings
from django.db import models


class Conversation(models.Model):
    """A conversation with the Agri AI Assistant."""

    owner = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        related_name='conversations',
        on_delete=models.CASCADE,
    )
    started_at = models.DateTimeField(auto_now_add=True)
    last_message_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        db_table = 'tblconversation'
        ordering = ['-started_at']
        indexes = [
            models.Index(fields=['owner', 'started_at'], name='conversation_owner_started_idx'),
        ]

    @property
    def message_count(self):
        return Message.objects.filter(conversation=self).count()

    def __str__(self):
        return f'{self.owner} conversation from {self.started_at:%Y-%m-%d}'


class Message(models.Model):
    """A single message inside an Agri AI Assistant conversation."""

    conversation = models.ForeignKey(
        Conversation,
        related_name='messages',
        on_delete=models.CASCADE,
    )
    sender = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        related_name='ai_messages',
        null=True,
        blank=True,
        on_delete=models.CASCADE,
        help_text='The user who sent the message; null for assistant/system messages.',
    )
    body = models.TextField(blank=True)
    image = models.ImageField(
        upload_to='chat_images/',
        null=True,
        blank=True,
        help_text='Optional crop photo attached to the message.',
    )
    image_content_type = models.CharField(max_length=100, blank=True)
    image_size = models.PositiveIntegerField(null=True, blank=True, help_text='Image size in bytes.')
    client_request_id = models.UUIDField(null=True, blank=True, unique=True, editable=False)
    reply_to = models.OneToOneField(
        'self',
        related_name='assistant_reply',
        null=True,
        blank=True,
        on_delete=models.CASCADE,
    )
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'tblmessage'
        ordering = ['created_at']
        indexes = [
            models.Index(fields=['conversation', 'created_at'], name='message_conversation_idx'),
        ]

    def __str__(self):
        sender = self.sender.username if self.sender else 'assistant'
        label = self.body[:50] if self.body else '(image)'
        return f'{sender}: {label}'

    @property
    def has_image(self):
        return bool(self.image)



class CropDiagnosis(models.Model):
    """An image-based crop disease, pest, or nutrient diagnosis generated by the AI Assistant."""

    user = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        related_name='crop_diagnoses',
        on_delete=models.CASCADE,
    )
    conversation = models.ForeignKey(
        Conversation,
        related_name='diagnoses',
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
    )
    message = models.ForeignKey(
        Message,
        related_name='diagnoses',
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
    )
    crop_name = models.CharField(max_length=150, blank=True, help_text='Identified or user-specified crop')
    image = models.ImageField(upload_to='diagnoses/', help_text='Analyzed crop photo')
    observed_symptoms = models.TextField(help_text='Visual symptoms noted on leaf, stem, fruit, or pest')
    possible_disease = models.CharField(max_length=255, help_text='Suggested disease, pest, or nutrient issue')
    confidence_level = models.CharField(max_length=50, default='Moderate', help_text='e.g. High, Moderate, Low / Uncertainty note')
    confidence_score = models.FloatField(default=0.7, help_text='Estimated confidence 0.0 to 1.0')
    contributing_factors = models.TextField(blank=True, help_text='Environmental or weather factors')
    treatment_recommendations = models.TextField(blank=True, help_text='Recommended practical next steps and care')
    preventive_measures = models.TextField(blank=True, help_text='Management and prevention strategies')
    technician_advice = models.TextField(blank=True, help_text='Guidance on when to contact an agricultural technician')
    is_confirmed = models.BooleanField(default=False, help_text='Whether confirmed by on-site inspection or agricultural expert')
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        db_table = 'tblcropdiagnosis'
        ordering = ['-created_at']
        indexes = [
            models.Index(fields=['user', '-created_at'], name='cropdiag_user_created_idx'),
        ]

    def __str__(self):
        return f'{self.crop_name or "Crop"} - {self.possible_disease} ({self.created_at:%Y-%m-%d})'
